/**
 * Traduit une clé, avec interpolation `{var}`.
 * Une clé absente renvoie la valeur française si elle existe, sinon la clé
 * elle-même (visible en développement, jamais cassant).
 */
export function t(key, vars) {
  const dict = MESSAGES[current] || MESSAGES[SITE.defaultLang];
  let value = dict?.[key];
  if (value === undefined) value = MESSAGES[SITE.defaultLang]?.[key];
  if (value === undefined) {
    if (typeof console !== "undefined") console.warn("[i18n] clé manquante :", key);
    return key;
  }
  if (!vars) return value;
  return String(value).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

/** Pluriel simple : `tp("clé", n)` utilise `clé` ou `clé.one`. */
export function tp(key, count, vars) {
  const suffix = Number(count) === 1 ? ".one" : "";
  const dict = MESSAGES[current] || MESSAGES[SITE.defaultLang];
  const candidate = dict?.[key + suffix] !== undefined ? key + suffix : key;
  return t(candidate, { ...vars, n: count, count });
}

/**
 * Applique les traductions à un sous-arbre (tout le document par défaut).
 *
 *   data-i18n="clé"                 → textContent
 *   data-i18n-html="clé"            → innerHTML (contenu enrichi maîtrisé)
 *   data-i18n-attr="clé1;clé2"      → attributs listés (placeholder, title…)
 *   data-i18n-placeholder="clé"     → attribut correspondant
 *   data-i18n-title / -aria-label   → idem
 */
export function applyTranslations(root = document) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (key) node.textContent = t(key);
  });
  root.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.getAttribute("data-i18n-html");
    if (key) node.innerHTML = t(key);
  });
  root.querySelectorAll("[data-i18n-attr]").forEach((node) => {
    node
      .getAttribute("data-i18n-attr")
      .split(";")
      .map((pair) => pair.trim())
      .filter(Boolean)
      .forEach((pair) => {
        const [attr, key] = pair.split(":").map((part) => part && part.trim());
        if (attr && key) node.setAttribute(attr, t(key));
      });
  });
  // `data-i18n-placeholder`, `data-i18n-title`, `data-i18n-aria-label`…
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria-label")));
  });
}

/** Change la langue, persiste le choix et prévient les modules abonnés. */
export function setLang(lang) {
  const next = normaliseLang(lang);
  if (!SUPPORTED.includes(next)) return current;
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* stockage indisponible : le choix vaut pour la page courante */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
    document.documentElement.dataset.lang = next;
    document.title = document.title; // no-op, conservé pour la lisibilité
    applyTranslations(document);
  }
  if (typeof window !== "undefined" && typeof window.dispatchEvent === "function") {
    window.dispatchEvent(new CustomEvent("cg:lang", { detail: { lang: next } }));
  }
  return current;
}

