const SUPPORTED = SITE.langs?.length ? SITE.langs : ["fr", "en"];
const LOCALES = { fr: "fr-CM", en: "en-GB" };

function normaliseLang(value) {
  const short = String(value || "").slice(0, 2).toLowerCase();
  return SUPPORTED.includes(short) ? short : SITE.defaultLang;
}

function readLang() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) return normaliseLang(stored);
  } catch {
    /* stockage indisponible (navigation privée) */
  }
  const nav = (typeof navigator !== "undefined" && (navigator.language || "")) || "fr";
  return normaliseLang(nav);
}

let current = typeof window === "undefined" ? SITE.defaultLang : readLang();

export function getLang() {
  return current;
}

export function availableLangs() {
  return SUPPORTED.slice();
}

const LANG_LABELS = { fr: "Français", en: "English" };

/** Nom natif d'une langue (`fr` → « Français »). */
export function langLabel(lang) {
  return LANG_LABELS[lang] || lang;
}

