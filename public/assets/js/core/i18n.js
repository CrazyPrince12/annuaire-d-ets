function locale() {
  return LOCALES[current] || LOCALES[SITE.defaultLang] || "fr-FR";
}

/** 12500 → « 12 500 » (espaces insécables comprises). */
export function formatNumber(value, options = {}) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "—";
  try {
    return new Intl.NumberFormat(locale(), options).format(number);
  } catch {
    return String(number);
  }
}

/** 2500 → « 2 500 FCFA » ; `compact` → « 2,5 k FCFA ». */
export function formatCurrency(value, { compact = false } = {}) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "—";
  if (compact && Math.abs(number) >= 1000) {
    const thousands = number / 1000;
    return `${formatNumber(thousands, { maximumFractionDigits: 1 })} k FCFA`;
  }
  return `${formatNumber(Math.round(number))} FCFA`;
}

function toDate(value) {
  if (value instanceof Date) return Number.isNaN(value.getTime()) ? null : value;
  if (value === null || value === undefined || value === "") return null;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? null : date;
}

/**
 * Date lisible. `style` : "short" (12 nov.), "medium" (12 nov. 2026),
 * "long" (jeudi 12 novembre 2026), "time" (14:32).
 */
export function formatDate(value, style = "medium") {
  const date = toDate(value);
  if (!date) return "";
  const options =
    style === "short"
      ? { day: "2-digit", month: "short" }
      : style === "long"
        ? { weekday: "long", day: "numeric", month: "long", year: "numeric" }
        : style === "time"
          ? { hour: "2-digit", minute: "2-digit" }
          : { day: "numeric", month: "short", year: "numeric" };
  try {
    return new Intl.DateTimeFormat(locale(), options).format(date);
  } catch {
    return date.toISOString().slice(0, 10);
  }
}

/** « 12 nov. 2026 · 14:32 ». */
export function formatDateTime(value) {
  const date = toDate(value);
  if (!date) return "";
  return `${formatDate(date, "medium")} · ${formatDate(date, "time")}`;
}

/** « il y a 3 jours », « dans 2 heures ». */
export function formatRelative(value) {
  const date = toDate(value);
  if (!date) return "";
  const diff = date.getTime() - Date.now();
  const future = diff > 0;
  const minutes = Math.round(Math.abs(diff) / 60_000);
  const fr = current === "fr";

  const say = (amount, unit) => {
    const plural = amount > 1;
    if (fr) {
      const units = { min: "minute", h: "heure", j: "jour", sem: "semaine", mois: "mois" };
      const label = units[unit];
      const word = plural && label !== "mois" ? `${label}s` : label;
      return future ? `dans ${amount} ${word}` : `il y a ${amount} ${word}`;
    }
    const units = { min: "minute", h: "hour", j: "day", sem: "week", mois: "month" };
    const word = plural ? `${units[unit]}s` : units[unit];
    return future ? `in ${amount} ${word}` : `${amount} ${word} ago`;
  };

  if (minutes < 1) return fr ? "à l'instant" : "just now";
  if (minutes < 60) return say(minutes, "min");
  const hours = Math.round(minutes / 60);
  if (hours < 24) return say(hours, "h");
  const days = Math.round(hours / 24);
  if (days < 7) return say(days, "j");
  const weeks = Math.round(days / 7);
  if (weeks < 5) return say(weeks, "sem");
  const months = Math.round(days / 30);
  if (months < 12) return say(months, "mois");
  return formatDate(date, "medium");
}

